/// Returns the visible stringtable-like label for one graphics toggle.
const fn graphics_toggle_label(
    options: &ShellOptionsState,
    field: ShellOptionField,
    on_label: &'static str,
    off_label: &'static str,
) -> &'static str {
    if options.bool_option(field) {
        on_label
    } else {
        off_label
    }
}

